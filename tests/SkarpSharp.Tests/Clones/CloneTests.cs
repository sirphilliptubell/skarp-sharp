    [Test]
    public async Task Forwarding_methods_are_not_near_misses()
    {
        static string Forward(string type, string target) => $$"""
            class {{type}}
            {
                public Task<int> Send(Request request, CancellationToken token)
                {
                    ArgumentNullException.ThrowIfNull(request);
                    return _inner.{{target}}(
                        request.Address,
                        request.Body,
                        request.Headers,
                        request.Timeout,
                        request.Retries,
                        request.Priority,
                        token);
                }
            }
