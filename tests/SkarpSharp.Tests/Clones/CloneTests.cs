/// <summary>Helpers: analyze in-memory files with the clone token streams, as a full run does.</summary>
public static class CloneHost
{
    public sealed record Source(string Path, string Code, bool Test = false, bool Generated = false);

    public static AnalysisResult Run(IEnumerable<Source> sources, IReadOnlyList<string>? overrides = null, bool near = false,
        CloneMode mode = CloneMode.TokensAndUnits)
    {
        var files = sources.Select(s =>
        {
            var code = s.Generated ? "// <auto-generated/>\n" + s.Code : s.Code;
            var f = Analyzer.AnalyzeText(SourceText.From(code), s.Path, mode);
            f.TestCode = s.Test;
            return f;
        }).ToList();
        var result = new AnalysisResult { Files = files };
        Aggregation.Fill(result, false);
        FindingEngine.Apply(result, Settings(overrides, near), false);
        return result;
    }

    public static RuleSettings Settings(IReadOnlyList<string>? overrides = null, bool near = false) =>
        RuleSettings.Resolve("default", null, overrides ?? [], disabledRules: near ? [] : [RuleIds.DuplicateCodeNear]);

    public static List<Finding> Clones(AnalysisResult r, string rule = RuleIds.DuplicateCode) => [.. (r.Findings ?? []).Where(f => f.Rule == rule)];

    /// <summary>
    /// A class with one method whose body has <paramref name="statements"/> statements of pseudo-random shapes (one per
    /// line, about 10 to 16 tokens each; the same seed gives the same code, different seeds different structure), so the
    /// code is not periodic and does not match itself.
    /// </summary>
    public static string Method(string type, string method, int statements, string variable = "total", int seed = 0)
    {
        string[] shapes =
        [
            "{0} += Compute(input, factor);",
            "if (input > factor) {0} -= input;",
            "factor = factor * 2 + {0} % 3;",
            "{0} ^= Lookup[input & 15];",
            "input = Math.Max(input, {0} - factor);",
            "{0} += items.Count(x => x.Size > factor);",
            "Log.Write(\"step\", {0});",
            "{0} = checked({0} + input * factor);",
            "if ({0} > 1000) return {0};",
            "factor += input switch {{ 0 => 1, 1 => 2, _ => 3 }};",
            "{0} -= items[input % items.Length].Weight;",
            "while (factor > 100) factor /= 2;",
            "input = ({0} + factor) >> 1;",
            "{0} += (int)Math.Round(input * 0.5);",
            "cache[input] = {0};",
            "{0} |= 1 << (factor & 7);",
        ];
        uint state = (uint)(seed * 7919 + 17);
        var lines = Enumerable.Range(0, statements).Select(_ =>
        {
            state = state * 1664525 + 1013904223;
            return "        " + string.Format(System.Globalization.CultureInfo.InvariantCulture, shapes[(state >> 20) % (uint)shapes.Length], variable);
        });
        return $$"""
            namespace N;
            public class {{type}}
            {
                public int {{method}}(int input, int factor)
                {
                    int {{variable}} = 0;
            {{string.Join("\n", lines)}}
                    return {{variable}};
                }
            }
            """;
    }
}

/// <summary>
/// Token-based clone detection: worked examples and expected results (exact and consistent renames match,
/// inconsistent renames do not, nothing below the minimum, clones within one file, tests and generated code, ids
/// stable across runs and file orders).
/// </summary>
public sealed class CloneTests
{
    static CloneHost.Source S(string path, string code, bool test = false, bool generated = false) => new(path, code, test, generated);

    static CloneFile Tokens(string code) =>
        CloneTokens.Collect(CSharpSyntaxTree.ParseText(code, Analyzer.ParseOptions), SourceText.From(code), units: false);

    static string Rename(string code, string type) => code.Replace("class A", "class " + type, StringComparison.Ordinal);

    [Test]
    public async Task Worked_example_1_token_count()
    {
        // 31 Roslyn tokens; += is one token.
        await Assert.That(Tokens("int Sum(int[] a) { int s = 0; foreach (var x in a) { s += x; } return s; }").Count).IsEqualTo(31);
    }

    [Test]
    public async Task Usings_attributes_and_namespace_parts_are_left_out_as_run_breaks()
    {
        var f = Tokens("using System;\nnamespace N.M;\n[Obsolete] class C { }");
        await Assert.That(f.Count).IsEqualTo(4); // class C { }
        await Assert.That((f.Flags[0] & TokenFlags.Break) != 0).IsTrue();
    }

    [Test]
    public async Task Worked_example_2_one_maximal_match_per_shared_run()
    {
        // Two identical files: one group whose instances are the whole class (one maximal match, not one per window).
        var code = CloneHost.Method("A", "Run", 12);
        var g = await Assert.That(CloneHost.Clones(CloneHost.Run([S("a/A.cs", code), S("b/A.cs", code)]))).HasSingleItem();
        await Assert.That(g.Clone!.Kind).IsEqualTo("exact");
        await Assert.That(g.Clone.Instances.Count).IsEqualTo(2);
        await Assert.That(g.Clone.Tokens).IsEqualTo(Tokens(code).Count);
    }

    [Test]
    public async Task Worked_example_3_type_1_ignores_comments_and_line_breaks()
    {
        var a = CloneHost.Method("A", "Run", 12);
        var b = a.Replace("int total = 0;", "int total = 0; // start", StringComparison.Ordinal).Replace("(int input, int factor)", "(int input,\n        int factor)", StringComparison.Ordinal);
        var g = await Assert.That(CloneHost.Clones(CloneHost.Run([S("A.cs", a), S("B.cs", b)]))).HasSingleItem();
        await Assert.That(g.Clone!.Kind).IsEqualTo("exact");
        // A different type name makes the copy renamed (Type 2).
        await Assert.That((await Assert.That(CloneHost.Clones(CloneHost.Run([S("A.cs", a), S("B.cs", Rename(b, "B"))]))).HasSingleItem()).Clone!.Kind).IsEqualTo("renamed");
    }

    [Test]
    public async Task Worked_example_3_small_methods_are_below_the_default_minimum_but_match_with_a_lower_one()
    {
        const string code = "class C { int Sum(int[] a) { int s = 0; foreach (var x in a) { s += x; } return s; } }";
        var files = new[] { S("A.cs", code), S("B.cs", code) };
        await Assert.That(CloneHost.Clones(CloneHost.Run(files))).IsEmpty();
        var g = await Assert.That(CloneHost.Clones(CloneHost.Run(files, ["duplicate-code.notice.tokens=20", "duplicate-code.notice.lines=1"]))).HasSingleItem();
        await Assert.That(g.Clone!.Tokens).IsEqualTo(31 + 4); // the method and class C { }
    }

    [Test]
    public async Task Worked_example_4_consistent_rename_matches_and_inconsistent_does_not()
    {
        var a = CloneHost.Method("A", "Run", 30, "total");
        var renamed = CloneHost.Method("B", "Go", 30, "sum");
        var g = await Assert.That(CloneHost.Clones(CloneHost.Run([S("A.cs", a), S("B.cs", renamed)]))).HasSingleItem();
        await Assert.That(g.Clone!.Kind).IsEqualTo("renamed");
        await Assert.That(g.Clone.Instances.Count).IsEqualTo(2);

        // Inconsistent: one "input" in the middle becomes "factor" (x = x + x against d = a + b): no copy spans that line.
        var lines = a.Split('\n');
        int mid = Enumerable.Range(lines.Length / 2 - 3, lines.Length).First(i => lines[i].Contains("input", StringComparison.Ordinal));
        int at = lines[mid].IndexOf("input", StringComparison.Ordinal);
        lines[mid] = lines[mid][..at] + "factor" + lines[mid][(at + "input".Length)..];
        var found = CloneHost.Clones(CloneHost.Run([S("A.cs", a), S("B.cs", Rename(string.Join('\n', lines), "B"))]));
        await Assert.That(found).DoesNotContain(f => f.Clone!.Instances.Any(i => i.Path == "B.cs" && i.StartLine <= mid + 1 && i.EndLine >= mid + 1));
    }

    [Test]
    public async Task Baker_codes_tell_consistent_from_inconsistent_renames()
    {
        var c = CloneCorpus.Build([("A.cs", Tokens("d = a + b;")), ("B.cs", Tokens("s = p + q;")), ("C.cs", Tokens("x = x + x;"))]);
        bool Same(int f1, int f2)
        {
            int a = c.FileStart[f1], b = c.FileStart[f2];
            return Enumerable.Range(0, 6).All(k => c.Equal(a + k, a, b + k, b));
        }
        await Assert.That(Same(0, 1)).IsTrue();
        await Assert.That(Same(0, 2)).IsFalse();
    }

    [Test]
    public async Task Worked_example_5_keywords_stay()
    {
        // async and await are keywords, not identifiers: they are never renamed away.
        var f = Tokens("async Task F() { await G(); }");
        var plain = Tokens("Task F() { G(); }");
        await Assert.That(f.Flags[0] & TokenFlags.Ident).IsEqualTo(0);
        await Assert.That(plain.Flags[0] & TokenFlags.Ident).IsNotEqualTo(0);
        const int awaitToken = 6; // async Task F ( ) { await
        await Assert.That(f.Flags[awaitToken] & TokenFlags.Ident).IsEqualTo(0);
        var code = CloneHost.Method("A", "Run", 12);
        var asyncCode = code.Replace("public int Run", "public async Task<int> Run", StringComparison.Ordinal)
            .Replace("        total", "        await Task.Yield(); total", StringComparison.Ordinal);
        await Assert.That(CloneHost.Clones(CloneHost.Run([S("A.cs", code), S("B.cs", Rename(asyncCode, "B"))]))).IsEmpty();
    }

    [Test]
    public async Task Worked_example_6_group_of_three_and_the_duplicated_lines_share()
    {
        var code = CloneHost.Method("A", "Run", 12);
        var r = CloneHost.Run([S("A.cs", code), S("B.cs", Rename(code, "B")), S("C.cs", Rename(code, "C"))]);
        var g = await Assert.That(CloneHost.Clones(r)).HasSingleItem();
        await Assert.That(g.Clone!.Instances.Count).IsEqualTo(3);
        await Assert.That(g.Clone.Instances.Select(i => i.Path)).IsEquivalentTo(["A.cs", "B.cs", "C.cs"], CollectionOrdering.Matching);
        int perCopy = g.Clone.Instances[0].Lines;
        await Assert.That(g.Clone.DuplicatedLines).IsEqualTo(3 * perCopy);
        var d = r.Repository.Duplication!;
        await Assert.That((d.Groups, d.Instances, d.DuplicatedLines)).IsEqualTo((1, 3, 3 * perCopy));
        await Assert.That(d.Share).IsEqualTo(Math.Round(3.0 * perCopy / r.Repository.Lines.Source, 4));
        await Assert.That(g.Value).IsEqualTo(3 * perCopy); // copies x lines
        await Assert.That(g.Metric).IsEqualTo("copiedLines");
    }

